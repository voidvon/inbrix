// Command gen regenerates site/docs from the repo's canonical markdown.
//
// site/docs used to be a byte-for-byte copy of docs/ (plus ROADMAP.md and
// CHANGELOG.md) with lowercased filenames, produced by scripts/sync-site-docs.mjs.
// That gate only ever compared source bytes against copy bytes, so it was blind
// to the thing that actually breaks for a reader: a link that is perfectly valid
// inside the repo and dead inside the published bundle. site/ ships eight
// markdown files and a screenshot folder — nothing else. Every link to
// ../config.toml.example, TASKS.md, README.md, or docs/screenshots/README.md was
// a 404, and every heading anchor written GitHub-style (#shared-object-storage-
// vulos_storage_broker_secret) missed the id site/docs.html actually assigns.
//
// So docs/ is now the single source and site/docs is generated: the same prose,
// with every link re-pointed at what the site will really serve.
//
// What the site really serves, and therefore what the rewriting targets:
//
//   - site/docs.html is a single-page viewer. It fetches ./docs/<name>.md and
//     renders it with marked, so relative URLs in the rendered HTML resolve
//     against site/, not site/docs/.
//   - Its `enhance()` step (rule 5) rewrites any href ending in "<base>.md"
//     to in-page navigation "#<slug>/<fragment>" when <base>.md is one of the
//     published chapters — matched case-insensitively on the BASENAME only.
//     So a generated sibling link is written bare: "api.md#attachments".
//   - Its rule 4 rewrites image sources matching (../)*(docs/)?screenshots/<f>
//     to ./screenshots/<f>, which is where the bundle keeps the PNGs.
//   - Heading ids come from `slugify()` over h2/h3 text only, and that slugify
//     DELETES backticks and underscores and COLLAPSES runs of hyphens. GitHub's
//     slugger does neither. anchorsFor/fuzzyAnchor below reproduce the viewer's
//     rule so a source link written for GitHub still lands on the site.
//   - The hash router treats "#foo" as a document slug, so a bare in-page
//     fragment navigates the reader to a different chapter. Bare fragments are
//     therefore rewritten to "<self>.md#foo".
//
// Anything that cannot resolve inside the bundle becomes an absolute repo URL
// rather than a dead relative path. gen_test.go fails on drift AND on any link
// or anchor that would not resolve, so the site cannot ship either.
//
// Usage:
//
//	go run ./site/gen      # rewrite site/docs
//	go test ./site/gen     # verify site/docs is current and link-clean (CI)
package main

import (
	"fmt"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"strings"
)

// repoURL is where links that cannot resolve inside the site bundle are sent.
const repoURL = "https://github.com/vul-os/lilmail/blob/main/"

// banner marks the output as generated. It is an HTML comment, so the markdown
// viewer renders it as nothing.
const banner = "<!-- Generated from %s by `go run ./site/gen`. Do not edit this file. -->\n"

// page is one published chapter: a repo-relative source and the filename it
// takes inside site/docs (which must match the DOCS table in site/docs.html).
type page struct {
	src string
	dst string
}

// pages is what the site bundle ships, in the nav order site/docs.html uses.
var pages = []page{
	{"docs/GETTING-STARTED.md", "getting-started.md"},
	{"docs/CONFIGURATION.md", "configuration.md"},
	{"docs/API.md", "api.md"},
	{"docs/SIGNING.md", "signing.md"},
	{"docs/ARCHITECTURE.md", "architecture.md"},
	{"docs/SCREENSHOTS.md", "screenshots.md"},
	{"ROADMAP.md", "roadmap.md"},
	{"CHANGELOG.md", "changelog.md"},
}

// imageExts are the targets rule 4 in site/docs.html can re-point at the
// bundle's screenshot folder. Everything else that leaves the bundle becomes an
// absolute repo URL.
var imageExts = map[string]bool{".png": true, ".jpg": true, ".jpeg": true, ".gif": true, ".svg": true, ".webp": true}

var (
	// linkRE matches a markdown link or image target.
	linkRE = regexp.MustCompile(`\]\(([^)\s]+)\)`)
	// fenceRE matches a fenced code-block delimiter. Link syntax inside a fence
	// is sample text, not a link, and must survive generation untouched.
	fenceRE = regexp.MustCompile("^\\s*(```|~~~)")
	// codeSpanRE matches an inline code span. `[Attachments](#attachments)`
	// written as code is prose *about* a link, not a link; rewriting it would
	// corrupt the sentence and checking it would report a link nobody can click.
	codeSpanRE = regexp.MustCompile("`+[^`]*`+")
	// headingRE matches the h2/h3 headings site/docs.html turns into anchors.
	headingRE = regexp.MustCompile(`^(#{2,3})\s+(.*)$`)
	// slugDropRE and slugKeepRE mirror site/docs.html's slugify(), in order.
	slugDropRE  = regexp.MustCompile("[`*_~]")
	slugKeepRE  = regexp.MustCompile(`[^\w\s-]`)
	slugSpaceRE = regexp.MustCompile(`\s+`)
	slugDashRE  = regexp.MustCompile(`-+`)
	// mdLinkTextRE unwraps [text](url) so a heading containing a link slugs
	// from its rendered text, the way textContent sees it.
	mdLinkTextRE = regexp.MustCompile(`\[([^\]]*)\]\([^)]*\)`)
	// fuzzyRE reduces an anchor to letters and digits, so a GitHub-style
	// fragment can be matched against the id the viewer assigns.
	fuzzyRE = regexp.MustCompile(`[^a-z0-9]`)
)

// slugify reproduces site/docs.html's slugify() exactly. Any drift here silently
// turns working anchors into dead ones, so it is pinned by TestSlugifyMatchesViewer.
func slugify(s string) string {
	s = strings.ToLower(strings.TrimSpace(s))
	s = slugDropRE.ReplaceAllString(s, "")
	s = slugKeepRE.ReplaceAllString(s, "")
	s = slugSpaceRE.ReplaceAllString(s, "-")
	return slugDashRE.ReplaceAllString(s, "-")
}

// fuzzy reduces an anchor to its letters and digits. "#1.10.0---2026-06-22" and
// "#1100-2026-06-22" share a fuzzy key, which is what lets a source link written
// for GitHub be re-pointed at the id the viewer really assigns.
func fuzzy(s string) string { return fuzzyRE.ReplaceAllString(strings.ToLower(s), "") }

// anchorsFor returns the heading ids site/docs.html will assign to a document —
// h2/h3 only, outside fenced code, deduplicated with the same "-2", "-3" suffix
// rule the viewer uses — plus a fuzzy-key index for remapping GitHub-style
// fragments. Fuzzy keys that two different headings share are dropped rather
// than guessed at.
func anchorsFor(body string) (ids map[string]bool, byFuzzy map[string]string) {
	ids = map[string]bool{}
	byFuzzy = map[string]string{}
	ambiguous := map[string]bool{}
	seen := map[string]bool{}
	fence := false
	for _, line := range strings.Split(body, "\n") {
		if fenceRE.MatchString(line) {
			fence = !fence
			continue
		}
		if fence {
			continue
		}
		m := headingRE.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		text := mdLinkTextRE.ReplaceAllString(m[2], "$1")
		base := slugify(text)
		if base == "" {
			base = "section"
		}
		id := base
		for n := 2; seen[id]; n++ {
			id = fmt.Sprintf("%s-%d", base, n)
		}
		seen[id] = true
		ids[id] = true
		k := fuzzy(id)
		if _, dup := byFuzzy[k]; dup {
			ambiguous[k] = true
			continue
		}
		byFuzzy[k] = id
	}
	for k := range ambiguous {
		delete(byFuzzy, k)
	}
	return ids, byFuzzy
}

// bundle is everything the generator needs to rewrite one document: the source
// bodies of every published chapter, and the anchors each one will expose.
type bundle struct {
	root    string
	bodies  map[string]string            // dst -> source body
	byPath  map[string]string            // repo-relative source path -> dst
	anchors map[string]map[string]bool   // dst -> heading ids
	fuzzy   map[string]map[string]string // dst -> fuzzy key -> heading id

	// escapes records every link the generator sent to an absolute repo URL,
	// with the repo-relative path it points at. The absolute-URL branch is an
	// escape hatch, and an unchecked escape hatch is how a dead link hides: a
	// link to a file that exists nowhere would become a tidy-looking
	// https://github.com/... 404 that no relative-path check ever sees.
	// TestSourceLinksExistInRepo walks this and demands each path be real.
	escapes []escape
}

// escape is one link the generator could not resolve inside the site bundle.
type escape struct {
	src  string // repo-relative source document
	line int    // 1-based line in that document
	rel  string // repo-relative path the absolute URL points at
	orig string // the target as written in the source
}

func loadBundle(root string) (*bundle, error) {
	b := &bundle{
		root:    root,
		bodies:  map[string]string{},
		byPath:  map[string]string{},
		anchors: map[string]map[string]bool{},
		fuzzy:   map[string]map[string]string{},
	}
	for _, p := range pages {
		raw, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(p.src)))
		if err != nil {
			return nil, fmt.Errorf("read %s: %w", p.src, err)
		}
		body := string(raw)
		b.bodies[p.dst] = body
		b.byPath[p.src] = p.dst
		b.anchors[p.dst], b.fuzzy[p.dst] = anchorsFor(body)
	}
	return b, nil
}

// resolveFragment maps a source fragment onto the id site/docs.html will really
// assign in dst. It returns "" when nothing matches, which is a dead anchor the
// test reports rather than something the generator papers over.
func (b *bundle) resolveFragment(dst, frag string) string {
	if frag == "" {
		return ""
	}
	if b.anchors[dst][frag] {
		return frag
	}
	if id, ok := b.fuzzy[dst][fuzzy(frag)]; ok {
		return id
	}
	return ""
}

// rewriteTarget maps one link target from a source document onto something the
// published bundle can serve. srcPath is the repo-relative source; dst is the
// published name of the document being generated (for self-fragments).
func (b *bundle) rewriteTarget(srcPath, dst string, line int, target string) string {
	if strings.HasPrefix(target, "http://") || strings.HasPrefix(target, "https://") ||
		strings.HasPrefix(target, "mailto:") {
		return target
	}

	file, frag := target, ""
	if i := strings.IndexByte(target, '#'); i != -1 {
		file, frag = target[:i], target[i+1:]
	}

	// A bare fragment is not in-page navigation here: the viewer's hash router
	// reads "#foo" as a document slug and sends the reader to another chapter.
	// Point it at this document explicitly so rule 5 turns it into "#slug/foo".
	if file == "" {
		if id := b.resolveFragment(dst, frag); id != "" {
			frag = id
		}
		return dst + "#" + frag
	}

	srcDir := path.Dir(filepath.ToSlash(srcPath))
	if srcDir == "." {
		srcDir = ""
	}
	rel := path.Clean(path.Join(srcDir, file))

	if to, ok := b.byPath[rel]; ok {
		if frag == "" {
			return to
		}
		if id := b.resolveFragment(to, frag); id != "" {
			frag = id
		}
		return to + "#" + frag
	}

	// Screenshots ship in the bundle under site/screenshots/; rule 4 in
	// site/docs.html re-points "screenshots/<f>" at "./screenshots/<f>".
	if imageExts[strings.ToLower(path.Ext(rel))] && strings.Contains(rel, "screenshots/") {
		return "screenshots/" + path.Base(rel)
	}

	b.escapes = append(b.escapes, escape{src: srcPath, line: line, rel: rel, orig: target})
	if frag != "" {
		return repoURL + rel + "#" + frag
	}
	return repoURL + rel
}

// outsideCode applies f to the stretches of a line that are outside inline code
// spans, leaving the spans themselves byte-identical.
func outsideCode(line string, f func(string) string) string {
	var out strings.Builder
	last := 0
	for _, loc := range codeSpanRE.FindAllStringIndex(line, -1) {
		out.WriteString(f(line[last:loc[0]]))
		out.WriteString(line[loc[0]:loc[1]])
		last = loc[1]
	}
	out.WriteString(f(line[last:]))
	return out.String()
}

// eachLink calls fn for every markdown link target in body that is really a
// link: outside fenced code blocks and outside inline code spans. It is the one
// definition of "a link in this document", shared by the generator and the gate
// so the two cannot disagree about what to check.
func eachLink(body string, fn func(line int, target string)) {
	fence := false
	for i, text := range strings.Split(body, "\n") {
		if fenceRE.MatchString(text) {
			fence = !fence
			continue
		}
		if fence {
			continue
		}
		outsideCode(text, func(seg string) string {
			for _, m := range linkRE.FindAllStringSubmatch(seg, -1) {
				fn(i+1, m[1])
			}
			return seg
		})
	}
}

// rewriteLinks rewrites every link target that is really a link.
func (b *bundle) rewriteLinks(srcPath, dst, body string) string {
	lines := strings.Split(body, "\n")
	fence := false
	for i, line := range lines {
		if fenceRE.MatchString(line) {
			fence = !fence
			continue
		}
		if fence {
			continue
		}
		lines[i] = outsideCode(line, func(seg string) string {
			return linkRE.ReplaceAllStringFunc(seg, func(m string) string {
				target := linkRE.FindStringSubmatch(m)[1]
				return "](" + b.rewriteTarget(srcPath, dst, i+1, target) + ")"
			})
		})
	}
	return strings.Join(lines, "\n")
}

// brokenEscapes returns the links the generator sent to an absolute repo URL
// that do not name a file the repository actually contains. Those are dead on
// GitHub as well as in the bundle, and without this the absolute-URL branch
// would launder any typo into a link no path check can falsify.
func (b *bundle) brokenEscapes() []escape {
	var bad []escape
	for _, e := range b.escapes {
		if _, err := os.Stat(filepath.Join(b.root, filepath.FromSlash(e.rel))); err != nil {
			bad = append(bad, e)
		}
	}
	return bad
}

// generate returns published filename -> generated content for every chapter,
// along with the bundle so callers can inspect what was rewritten.
func generate(root string) (map[string]string, *bundle, error) {
	b, err := loadBundle(root)
	if err != nil {
		return nil, nil, err
	}
	out := make(map[string]string, len(pages))
	for _, p := range pages {
		out[p.dst] = fmt.Sprintf(banner, p.src) + b.rewriteLinks(p.src, p.dst, b.bodies[p.dst])
	}
	return out, b, nil
}

// findRoot walks up from dir to the module root.
func findRoot(dir string) (string, error) {
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("no go.mod above %s", dir)
		}
		dir = parent
	}
}

func main() {
	cwd, err := os.Getwd()
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	root, err := findRoot(cwd)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	files, b, err := generate(root)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	dir := filepath.Join(root, "site", "docs")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	for name, body := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "gen:", err)
			os.Exit(1)
		}
	}
	fmt.Printf("gen: wrote %d docs to site/docs (%d links re-pointed out of the bundle)\n",
		len(files), len(b.escapes))

	// Written, then judged: regenerating must still resolve drift, but a link to
	// a file that exists nowhere is a failure the author has to see.
	if bad := b.brokenEscapes(); len(bad) > 0 {
		fmt.Fprintf(os.Stderr, "\ngen: %d link(s) point at a path this repository does not contain:\n", len(bad))
		for _, e := range bad {
			fmt.Fprintf(os.Stderr, "  %s:%d  %s  ->  %s (missing)\n", e.src, e.line, e.orig, e.rel)
		}
		fmt.Fprintln(os.Stderr, "\nFix the link in the source document; an absolute repo URL to a missing file is still a 404.")
		os.Exit(1)
	}
}
