// version_test.go is the landing-version drift gate.
//
// VERSION is not part of the release contract: release.yml derives the built
// binary's version from the git TAG it was triggered by (see "Verify tag
// matches declared version" in .github/workflows/release.yml), not from this
// file. So nothing ever forced VERSION forward, and on 2026-08-06 v1.14.0
// released while VERSION still said 1.13.0 — and site/index.html and
// site/docs.html, which display VERSION by convention, went stale right
// along with it.
//
// TestLandingVersionMatchesVERSION and TestDocsFooterVersionMatchesVERSION
// close the landing half of that gap. Each demands an EXACT match count, not
// "found at least one": a regex that stops matching because someone restyled
// the slug, dropped the "v" prefix, or renamed the class must fail loudly
// naming "could not find", never pass silently because it compared zero
// things against zero things.
//
// TestVersionMatchesLatestTag closes the other half — the thing that
// actually caused today's drift: VERSION can equal the landing and both still
// be stale together. It asserts VERSION equals the latest reachable git tag.
// That needs real tag history, which a shallow checkout (actions/checkout's
// default fetch-depth: 1, no tags) does not have. CI sets fetch-depth: 0 for
// this job specifically so the check is a real hard gate there; outside CI —
// a source tarball, a shallow local clone, a fork with no tags pushed — it
// skips with an explicit reason rather than failing on an environment problem
// it did not cause.
package main

import (
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
	"testing"
)

// readVersion reads and validates the repo's VERSION file. It fails closed:
// a missing file or a value that is not plain semver means every test below
// verified nothing, so it must not be treated as "version unknown, skip".
func readVersion(t *testing.T, r string) string {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join(r, "VERSION"))
	if err != nil {
		t.Fatalf("read VERSION: %v — the version-drift gate verified NOTHING", err)
	}
	v := strings.TrimSpace(string(raw))
	if !regexp.MustCompile(`^[0-9]+\.[0-9]+\.[0-9]+$`).MatchString(v) {
		t.Fatalf("VERSION contains %q, which is not a plain X.Y.Z semver — the version-drift gate "+
			"verified NOTHING", v)
	}
	return v
}

// majorMinor derives "X.Y" from a "X.Y.Z" VERSION, which is the form
// site/index.html's spec card shows ("No. 1.14").
func majorMinor(t *testing.T, version string) string {
	t.Helper()
	parts := strings.SplitN(version, ".", 3)
	if len(parts) < 2 {
		t.Fatalf("cannot derive major.minor from VERSION %q — the version-drift gate verified NOTHING", version)
	}
	return parts[0] + "." + parts[1]
}

// TestLandingVersionMatchesVERSION checks the two places site/index.html
// displays the version: the hero slug ("v1.14.0") and the spec card
// ("No. 1.14"). site/index.html is hand-authored, not generated by this
// package (site/gen only produces site/docs/*.md), so this reads the file
// directly rather than through generate().
func TestLandingVersionMatchesVERSION(t *testing.T) {
	r := root(t)
	version := readVersion(t, r)

	raw, err := os.ReadFile(filepath.Join(r, "site", "index.html"))
	if err != nil {
		t.Fatalf("read site/index.html: %v — the version-drift gate verified NOTHING", err)
	}
	html := string(raw)

	slugRE := regexp.MustCompile(`<div class="slug"><b>v([0-9]+\.[0-9]+\.[0-9]+)</b>`)
	slugMatches := slugRE.FindAllStringSubmatch(html, -1)
	if len(slugMatches) != 1 {
		t.Fatalf("found %d occurrence(s) of the hero slug version marker in site/index.html, want exactly "+
			"1 — either the markup was restyled and this regex no longer finds it, or it appears more than "+
			"once; either way the version was NOT verified. Looked for: %s",
			len(slugMatches), slugRE.String())
	}
	if got := slugMatches[0][1]; got != version {
		t.Errorf("site/index.html hero slug shows v%s but VERSION says %s", got, version)
	} else {
		t.Logf("hero slug: VERSION %q == site/index.html %q", version, "v"+got)
	}

	capRE := regexp.MustCompile(`<span>Specification</span><span>No\. ([0-9]+\.[0-9]+)</span>`)
	capMatches := capRE.FindAllStringSubmatch(html, -1)
	if len(capMatches) != 1 {
		t.Fatalf("found %d occurrence(s) of the spec-card version marker in site/index.html, want exactly "+
			"1 — the version was NOT verified. Looked for: %s", len(capMatches), capRE.String())
	}
	want := majorMinor(t, version)
	if got := capMatches[0][1]; got != want {
		t.Errorf("site/index.html spec card shows \"No. %s\" but VERSION (%s) implies \"No. %s\"", got, version, want)
	} else {
		t.Logf("spec card: VERSION %q == site/index.html \"No. %s\"", version, got)
	}
}

// TestDocsFooterVersionMatchesVERSION checks the sidebar footer in
// site/docs.html ("inbrix v1.14.0"). site/docs.html is hand-authored, not
// generated (site/gen only produces site/docs/*.md), so this reads the file
// directly.
func TestDocsFooterVersionMatchesVERSION(t *testing.T) {
	r := root(t)
	version := readVersion(t, r)

	raw, err := os.ReadFile(filepath.Join(r, "site", "docs.html"))
	if err != nil {
		t.Fatalf("read site/docs.html: %v — the version-drift gate verified NOTHING", err)
	}
	html := string(raw)

	footerRE := regexp.MustCompile(`inbrix v([0-9]+\.[0-9]+\.[0-9]+)<br>`)
	matches := footerRE.FindAllStringSubmatch(html, -1)
	if len(matches) != 1 {
		t.Fatalf("found %d occurrence(s) of the sidebar footer version marker in site/docs.html, want "+
			"exactly 1 — the version was NOT verified. Looked for: %s", len(matches), footerRE.String())
	}
	if got := matches[0][1]; got != version {
		t.Errorf("site/docs.html sidebar footer shows v%s but VERSION says %s", got, version)
	} else {
		t.Logf("docs footer: VERSION %q == site/docs.html %q", version, "v"+got)
	}
}

// TestVersionMatchesLatestTag asserts VERSION equals the latest git tag
// reachable from HEAD — the actual cause of today's drift (release.yml tags
// releases independently of VERSION, so nothing else ties them together).
//
// This needs tag history a shallow checkout does not have. It distinguishes
// "no tags reachable here" (skip, naming why) from a real mismatch (fail):
// skipping on missing history is not the same hollow-gate failure mode as
// swallowing a real mismatch, because CI's checkout step is configured with
// fetch-depth: 0 specifically so this job never hits the skip path there.
// TestReadmeVersionMatchesVERSION covers the two places README.md pins a
// version: the verify.sh --tag argument and the release archive name beside
// it. Both are instructions a reader will copy and run.
//
// This existed nowhere until now. The landing and the docs footer were gated
// and the README was not, so it could drift to a tag that no longer exists —
// which is exactly what happened to a sibling repo in this suite: its README
// told people to fetch a tag that had been deleted, and the first step of the
// quickstart 404'd. Same shape as the checks above: assert the marker is found
// EXACTLY once, so a restyle that stops matching fails loudly instead of
// verifying nothing.
func TestReadmeVersionMatchesVERSION(t *testing.T) {
	r := root(t)
	version := readVersion(t, r)

	raw, err := os.ReadFile(filepath.Join(r, "README.md"))
	if err != nil {
		t.Fatalf("read README.md: %v — the version-drift gate verified NOTHING", err)
	}
	readme := string(raw)

	for _, c := range []struct {
		name string
		re   *regexp.Regexp
		want string
	}{
		{"verify.sh --tag", regexp.MustCompile(`--tag v([0-9]+\.[0-9]+\.[0-9]+)`), version},
		{"release archive", regexp.MustCompile(`inbrix_([0-9]+\.[0-9]+\.[0-9]+)_[a-z0-9]+_[a-z0-9]+\.zip`), version},
	} {
		m := c.re.FindAllStringSubmatch(readme, -1)
		if len(m) != 1 {
			t.Fatalf("found %d occurrence(s) of the %s version marker in README.md, want exactly 1 — "+
				"the version was NOT verified. Looked for: %s", len(m), c.name, c.re.String())
		}
		if got := m[0][1]; got != c.want {
			t.Errorf("README.md %s shows %s but VERSION says %s", c.name, got, c.want)
		} else {
			t.Logf("README %s: VERSION %q == README %q", c.name, c.want, got)
		}
	}
}

func TestVersionMatchesLatestTag(t *testing.T) {
	r := root(t)
	version := readVersion(t, r)

	out, err := exec.Command("git", "-C", r, "describe", "--tags", "--abbrev=0").CombinedOutput()
	if err != nil {
		msg := strings.TrimSpace(string(out))
		if strings.Contains(msg, "No names found") || strings.Contains(msg, "No tags can describe") ||
			strings.Contains(msg, "not a git repository") || strings.Contains(msg, "fatal:") {
			t.Skipf("no git tag history reachable from this checkout (%s) — this check needs a non-shallow "+
				"clone or `git fetch --tags` (CI's checkout step sets fetch-depth: 0 for this job so it runs "+
				"for real there); skipping rather than failing on an environment problem it did not cause", msg)
		}
		t.Fatalf("git describe --tags --abbrev=0: %v (%s) — the tag-drift gate verified NOTHING", err, msg)
	}

	tag := strings.TrimSpace(string(out))
	tagVersion := strings.TrimPrefix(tag, "v")
	if tagVersion != version {
		t.Errorf("VERSION says %q but the latest git tag is %q (stripped: %q) — bump VERSION to match the "+
			"release that was just tagged", version, tag, tagVersion)
		return
	}
	t.Logf("VERSION %q matches latest tag %q", version, tag)
}
