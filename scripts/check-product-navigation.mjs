import assert from 'node:assert/strict';
import { chromium } from 'playwright';

const base = process.env.PRODUCT_TEST_URL || 'http://127.0.0.1:3097';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const products = [], categories = [];
const table = page.getByRole('table', { name: '产品库', exact: true });
const nav = () => page.getByRole('navigation', { name: '品牌与分类', exact: true });
const node = label => nav().getByRole('button').filter({ hasText: new RegExp(`^${label}`) });
const withinBrand = label => nav().locator('li').filter({ has: page.getByRole('button').filter({ hasText: new RegExp(`^${label}`) }) });
const total = count => page.getByTestId('products-page').locator('footer').getByText(`产品总数: ${count}`, { exact: true }).waitFor();
async function createProduct(name, brand, categoryId = '') {
  const response = await page.request.post(`${base}/api/products`, { data: { name, brand, categoryId, version: 0 } });
  assert(response.ok()); products.push((await response.json()).product);
}
try {
  assert.equal((await (await page.request.get(`${base}/api/capabilities`)).json()).productTestHarness, true);
  await page.goto(`${base}/products`);
  await page.getByRole('button', { name: '分类管理', exact: true }).click();
  const manager = page.getByRole('dialog');
  await manager.getByRole('textbox', { name: '分类名称' }).fill('疏水阀');
  await manager.getByRole('button', { name: '新增分类', exact: true }).click();
  await manager.getByRole('button', { name: '查看 / 编辑 疏水阀', exact: true }).waitFor();
  await manager.getByRole('textbox', { name: '分类名称' }).fill('浮球式疏水阀');
  await manager.getByRole('combobox', { name: '上级分类', exact: true }).click();
  await page.getByRole('option', { name: '疏水阀', exact: true }).click();
  await manager.getByRole('button', { name: '新增分类', exact: true }).click();
  await manager.getByRole('button', { name: '查看 / 编辑 浮球式疏水阀', exact: true }).waitFor();
  assert.equal(await manager.getByRole('button', { name: '删除 疏水阀', exact: true }).isDisabled(), true);
  await manager.getByRole('button', { name: '查看 / 编辑 疏水阀', exact: true }).click();
  await manager.getByRole('combobox', { name: '上级分类', exact: true }).click();
  assert.equal(await page.getByRole('option', { name: /疏水阀/ }).count(), 0, 'A category cannot be parented to itself or a descendant');
  await page.keyboard.press('Escape');
  await page.keyboard.press('Escape');
  await manager.waitFor({ state: 'hidden' });
  categories.push(...(await (await page.request.get(`${base}/api/product-categories`)).json()).categories);
  const root = categories.find(category => category.name === '疏水阀');
  const child = categories.find(category => category.name === '浮球式疏水阀');
  assert.equal(child.parentId, root.id);
  for (let i = 0; i < 13; i++) await createProduct(`浮球产品 ${i}`, '斯派莎克', child.id);
  await createProduct('父级产品', '斯派莎克', root.id);
  await createProduct('未归类产品', '斯派莎克');
  await createProduct('另一品牌浮球', '其他品牌', child.id);
  await createProduct('无品牌产品', '', child.id);
  await page.reload();
  await total(17);
  await node('斯派莎克').click();
  await total(15);
  await node('疏水阀').click();
  await total(14);
  assert.equal(await node('疏水阀').getAttribute('aria-current'), 'page');
  await node('浮球式疏水阀').click();
  await total(13);
  await page.getByRole('button', { name: '下一页', exact: true }).click();
  await page.locator('[aria-current=page][data-slot=pagination-link]').filter({ hasText: '2' }).waitFor();
  assert.equal(await table.getByRole('button', { name: /^查看 \/ 编辑/ }).count(), 1);
  await node('斯派莎克').click();
  await total(15);
  await page.locator('[aria-current=page][data-slot=pagination-link]').filter({ hasText: '1' }).waitFor();
  await node('未分类').click();
  await total(1);
  await table.getByRole('button', { name: '未归类产品', exact: true }).waitFor();
  await node('其他品牌').click();
  await total(1);
  await withinBrand('其他品牌').getByRole('button').filter({ hasText: /^浮球式疏水阀/ }).click();
  await table.getByRole('button', { name: '另一品牌浮球', exact: true }).waitFor();
  const search = page.getByRole('textbox', { name: '搜索型号、名称或规格关键词' });
  await search.fill('无匹配词');
  await total(0);
  assert.equal(await node('斯派莎克').innerText(), '斯派莎克\n15', 'Navigation counts must not be narrowed by search');
  await search.fill('');
  await total(1);
  await node('未设置品牌').click();
  await total(1);
  await table.getByRole('button', { name: '无品牌产品', exact: true }).waitFor();
  await node('斯派莎克').click();
  await withinBrand('斯派莎克').getByRole('button').filter({ hasText: /^浮球式疏水阀/ }).click();
  await total(13);
  await page.getByRole('button', { name: '新建产品', exact: true }).click();
  assert.equal(await page.getByLabel('品牌', { exact: true }).inputValue(), '斯派莎克');
  assert.equal(await page.getByRole('dialog').getByRole('combobox', { name: '分类', exact: true }).innerText(), '疏水阀 / 浮球式疏水阀');
  await page.keyboard.press('Escape');
  if (await page.getByRole('alertdialog').count()) await page.getByRole('alertdialog').getByRole('button', { name: '放弃修改', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.screenshot({ path: '/tmp/inbrix-brand-tree-desktop.png', animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '品牌与分类', exact: true }).click();
  await page.getByRole('dialog', { name: '品牌与分类', exact: true }).waitFor();
  await page.screenshot({ path: '/tmp/inbrix-brand-tree-mobile-menu.png', animations: 'disabled' });
  await node('其他品牌').click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await total(1);
  await table.getByRole('button', { name: '另一品牌浮球', exact: true }).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: '/tmp/inbrix-brand-tree-mobile-table.png', animations: 'disabled' });
  assert.deepEqual(errors, []);
  console.log('Brand/category trees, shared subcategories, counts, scoped search, pagination reset, unbranded/uncategorized products and mobile navigation passed.');
} finally {
  for (const product of products) await page.request.delete(`${base}/api/products/${product.id}?version=${product.version}`);
  for (const category of categories.sort((a, b) => Number(Boolean(b.parentId)) - Number(Boolean(a.parentId)))) await page.request.delete(`${base}/api/product-categories/${category.id}`);
  await browser.close();
}
