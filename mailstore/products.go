func productModelKey(s string) string {
	return strings.Map(func(r rune) rune {
		if unicode.IsLetter(r) || unicode.IsDigit(r) {
			return unicode.ToLower(r)
		}
		return -1
	}, s)
}

// Use overlapping CJK bigrams for substring retrieval and normal word tokens
// for Latin identifiers. No product names or domain vocabulary are hardcoded.
func productTokens(s string) []string {
	var result []string
	var word []rune
	var han []rune
	flushWord := func() {
		if len(word) > 0 {
			result = append(result, string(word))
			word = nil
		}
	}
	flushHan := func() {
		for _, r := range han {
			result = append(result, string(r))
		}
		for i := 0; i+1 < len(han); i++ {
			result = append(result, string(han[i:i+2]))
		}
		han = nil
	}
	for _, r := range strings.ToLower(s) {
		if unicode.Is(unicode.Han, r) {
			flushWord()
			han = append(han, r)
		} else if unicode.IsLetter(r) || unicode.IsDigit(r) {
			flushHan()
			word = append(word, r)
		} else {
			flushWord()
			flushHan()
		}
	}
	flushWord()
	flushHan()
	return result
}

func splitProductSections(s string) []ProductSection {
	runes := []rune(s)
	sections := []ProductSection{}
	start := 0
	heading := ""
	activeHeading := ""
	position := 0
	flush := func(end int) {
		if end > start {
			sections = append(sections, ProductSection{Index: len(sections), Heading: activeHeading, Offset: start, Length: end - start})
		}
		start = end
		activeHeading = heading
	}
	for _, line := range strings.SplitAfter(s, "\n") {
		trim := strings.TrimSpace(line)
		if strings.HasPrefix(trim, "#") {
			hashCount := len(trim) - len(strings.TrimLeft(trim, "#"))
			if hashCount <= 6 && len(trim) > hashCount && trim[hashCount] == ' ' {
				flush(position)
				heading = strings.TrimSpace(trim[hashCount:])
				if title := []rune(heading); len(title) > 120 {
					heading = string(title[:120])
				}
				activeHeading = heading
			}
		}
		length := utf8.RuneCountInString(line)
		if position-start+length > 1800 {
			flush(position)
		}
		for length > 1800 {
			position += 1800
			length -= 1800
			flush(position)
		}
		position += length
	}
	flush(len(runes))
	if len(sections) == 0 {
		sections = append(sections, ProductSection{Heading: "", Index: 0})
	}
	return sections
}

func (s *Store) SearchProducts(ctx context.Context, owner, query, category string, limit, offset int) (ProductSearchPage, error) {
	page := ProductSearchPage{Products: []ProductHit{}}
	if limit < 1 || limit > 20 || offset < 0 || offset > 100000 || utf8.RuneCountInString(query) > 200 {
		return page, invalidProduct("limit must be 1–20; offset 0–100000; query at most 200 characters")
	}
	where := `p.owner_id=?`
	args := []any{owner}
	if category != "" {
		where += ` AND p.category_id=?`
		args = append(args, category)
	}
	from := productJoin
	query = strings.TrimSpace(query)
	matched := query != ""
	if matched {
		tokens := productTokens(query)
		if len(tokens) == 0 {
			return page, nil
		}
		terms := make([]string, 0, len(tokens))
		for _, token := range tokens {
			terms = append(terms, `"`+strings.ReplaceAll(token, `"`, `""`)+`"`)
		}
		expression := strings.Join(terms, " AND ")
		// A normalized identifier is an alternative only for a single identifier,
		// so unrelated words cannot collapse into a spurious model match.
		if len(strings.Fields(query)) == 1 {
			expression = "(" + expression + ") OR metadata : \"" + productModelKey(query) + "\""
		}
		from += ` JOIN product_chunks ch ON ch.product_id=p.id JOIN product_chunks_fts ON product_chunks_fts.rowid=ch.id `
		where += ` AND product_chunks_fts MATCH ?`
		args = append(args, expression)
	}
	countSQL := `SELECT count(DISTINCT p.id)` + from + `WHERE ` + where
	if err := s.db.QueryRowContext(ctx, countSQL, args...).Scan(&page.Total); err != nil {
		return page, err
	}
	var statement string
	if matched {
		// Rank before deduplicating so each product contributes only its best hit.
		statement = `WITH hits AS MATERIALIZED (SELECT ` + productColumns + `,ch.section_index,ch.heading,ch.start_offset,ch.content,bm25(product_chunks_fts,5.0,1.0) AS score` + from + `WHERE ` + where + ` ORDER BY score,p.id,ch.section_index), best AS (SELECT *,row_number() OVER(PARTITION BY id ORDER BY score,section_index) AS n FROM hits) SELECT id,owner_id,name,brand,model,category_id,category_name,image_id,version,updated_at,section_index,heading,start_offset,content FROM best WHERE n=1 ORDER BY score,id LIMIT ? OFFSET ?`
	} else {
		statement = `SELECT ` + productColumns + `,0,'',0,substr(p.specification,1,240)` + from + `WHERE ` + where + ` ORDER BY p.updated_at DESC,p.id LIMIT ? OFFSET ?`
	}
	args = append(args, limit, offset)
	rows, err := s.db.QueryContext(ctx, statement, args...)
	if err != nil {
		return page, err
	}
	defer rows.Close()
	for rows.Next() {
		var hit ProductHit
		var content string
		if err := scanProduct(rows, &hit.Product, &hit.Section, &hit.Heading, &hit.Offset, &content); err != nil {
			return page, err
		}
		localOffset, snippet := productSnippet(content, query)
		hit.Offset += localOffset
		hit.Snippet = snippet
		page.Products = append(page.Products, hit)
	}
	if err := rows.Err(); err != nil {
		return page, err
	}
	page.HasMore = offset+len(page.Products) < page.Total
	if page.HasMore {
		page.NextOffset = offset + len(page.Products)
	}
	return page, nil
}

func (s *Store) ReadProduct(ctx context.Context, owner, id string, version int64, offset, length int) (ProductRead, error) {
	var result ProductRead
	if offset < 0 || length < 1 || length > 4000 {
		return result, invalidProduct("offset must be nonnegative; length 1–4000")
	}
	p, err := s.GetProduct(ctx, owner, id)
	if err != nil {
		return result, err
	}
	if version != 0 && version != p.Version {
		return result, ErrProductConflict
	}
	r := []rune(p.Specification)
	if offset > len(r) {
		return result, invalidProduct("offset exceeds specification length")
	}
	end := min(offset+length, len(r))
	result.Content = string(r[offset:end])
	result.Offset = offset
	result.TotalLength = len(r)
	result.HasMore = end < len(r)
	result.NextOffset = end
	sections := splitProductSections(p.Specification)
	result.SectionCount = len(sections)
	start := 0
	for start+1 < len(sections) && sections[start+1].Offset <= offset {
		start++
	}
	sectionEnd := min(start+20, len(sections))
	result.Sections = sections[start:sectionEnd]
	result.HasMoreSections = sectionEnd < len(sections)
	p.Specification = ""
	result.Product = p
	return result, nil
}

func productSnippet(content, query string) (int, string) {
	runes := []rune(content)
	start := 0
	lower := strings.ToLower(content)
	for _, term := range strings.Fields(query) {
		if at := strings.Index(lower, strings.ToLower(term)); at >= 0 {
			start = max(0, utf8.RuneCountInString(lower[:at])-80)
			break
		}
	}
	return start, string(runes[start:min(start+400, len(runes))])
}
