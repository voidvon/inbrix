var ErrProductConflict = errors.New("product changed; reload the latest version")
var ErrProductInvalid = errors.New("invalid product data")

const MaxProductSpecificationRunes = 100_000
const MaxProductImageBytes = 2 * 1024 * 1024

type ProductCategory struct {
	ID           string `json:"id"`
	Name         string `json:"name"`
	ProductCount int    `json:"productCount"`
}

type Product struct {
	ID            string    `json:"id"`
	OwnerID       string    `json:"-"`
	Name          string    `json:"name"`
	Brand         string    `json:"brand"`
	Model         string    `json:"model"`
	CategoryID    string    `json:"categoryId"`
	CategoryName  string    `json:"categoryName"`
	Specification string    `json:"specification,omitempty"`
	ImageID       string    `json:"imageId"`
	ImageURL      string    `json:"imageUrl,omitempty"`
	Version       int64     `json:"version"`
	UpdatedAt     time.Time `json:"updatedAt"`
}

type ProductInput struct {
	Name          string `json:"name"`
	Brand         string `json:"brand"`
	Model         string `json:"model"`
	CategoryID    string `json:"categoryId"`
	Specification string `json:"specification"`
	// nil keeps the existing image; empty explicitly removes it.
	ImageDataURL *string `json:"imageDataUrl,omitempty"`
	Version      int64   `json:"version"`
}

type ProductSection struct {
	Index   int    `json:"index"`
	Heading string `json:"heading"`
	Offset  int    `json:"offset"`
	Length  int    `json:"length"`
}

type ProductHit struct {
	Product
	Section int    `json:"section"`
	Heading string `json:"heading"`
	Offset  int    `json:"offset"`
	Snippet string `json:"snippet"`
}

type ProductSearchPage struct {
	Products   []ProductHit `json:"products"`
	Total      int          `json:"total"`
	HasMore    bool         `json:"hasMore"`
	NextOffset int          `json:"nextOffset"`
}

type ProductRead struct {
	Product         Product          `json:"product"`
	Sections        []ProductSection `json:"sections"`
	Content         string           `json:"content"`
	Offset          int              `json:"offset"`
	NextOffset      int              `json:"nextOffset"`
	HasMore         bool             `json:"hasMore"`
	TotalLength     int              `json:"totalLength"`
	SectionCount    int              `json:"sectionCount"`
	HasMoreSections bool             `json:"hasMoreSections"`
}

func (s *Store) migrateProducts(ctx context.Context) error {
	for _, statement := range []string{
		`CREATE TABLE IF NOT EXISTS product_categories (id TEXT PRIMARY KEY, owner_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE, name TEXT NOT NULL, UNIQUE(owner_id,name))`,
		`CREATE TABLE IF NOT EXISTS product_images (id TEXT PRIMARY KEY, owner_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE, content_type TEXT NOT NULL, data BLOB NOT NULL)`,
		`CREATE TABLE IF NOT EXISTS products (id TEXT PRIMARY KEY, owner_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE, name TEXT NOT NULL, brand TEXT NOT NULL DEFAULT '', model TEXT NOT NULL DEFAULT '', model_key TEXT NOT NULL DEFAULT '', category_id TEXT NOT NULL DEFAULT '', specification TEXT NOT NULL DEFAULT '', image_id TEXT NOT NULL DEFAULT '', version INTEGER NOT NULL, updated_at INTEGER NOT NULL)`,
		`CREATE INDEX IF NOT EXISTS idx_products_owner_model ON products(owner_id, model_key)`,
		`CREATE INDEX IF NOT EXISTS idx_products_owner_category ON products(owner_id, category_id, updated_at DESC, id)`,
		`CREATE TABLE IF NOT EXISTS product_chunks (id INTEGER PRIMARY KEY, product_id TEXT NOT NULL REFERENCES products(id) ON DELETE CASCADE, section_index INTEGER NOT NULL, heading TEXT NOT NULL, start_offset INTEGER NOT NULL, content TEXT NOT NULL)`,
		`CREATE INDEX IF NOT EXISTS idx_product_chunks_product ON product_chunks(product_id, section_index)`,
		// CJK bigrams are generated by productTokens rather than relying on
		// unicode61, which otherwise treats an entire Chinese sentence as one word.
		`CREATE VIRTUAL TABLE IF NOT EXISTS product_chunks_fts USING fts5(metadata, body, tokenize='unicode61 remove_diacritics 2')`,
		`CREATE TRIGGER IF NOT EXISTS product_chunks_delete AFTER DELETE ON product_chunks BEGIN DELETE FROM product_chunks_fts WHERE rowid=old.id; END`,
	} {
		if _, err := s.db.ExecContext(ctx, statement); err != nil {
			return fmt.Errorf("mailstore: migrate products: %w", err)
		}
	}
	return nil
}

func invalidProduct(message string) error { return fmt.Errorf("%w: %s", ErrProductInvalid, message) }

func (s *Store) ListProductCategories(ctx context.Context, owner string) ([]ProductCategory, error) {
	rows, err := s.db.QueryContext(ctx, `SELECT c.id,c.name,count(p.id) FROM product_categories c LEFT JOIN products p ON p.category_id=c.id AND p.owner_id=c.owner_id WHERE c.owner_id=? GROUP BY c.id ORDER BY c.name,c.id`, owner)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	result := []ProductCategory{}
	for rows.Next() {
		var c ProductCategory
		if err := rows.Scan(&c.ID, &c.Name, &c.ProductCount); err != nil {
			return nil, err
		}
		result = append(result, c)
	}
	return result, rows.Err()
}

func (s *Store) SaveProductCategory(ctx context.Context, owner, id, name string) (ProductCategory, error) {
	name = strings.TrimSpace(name)
	if owner == "" || name == "" || utf8.RuneCountInString(name) > 100 {
		return ProductCategory{}, invalidProduct("category name is required (max 100 characters)")
	}
	s.productMu.Lock()
	defer s.productMu.Unlock()
	if id == "" {
		var err error
		id, err = newID("pcat")
		if err != nil {
			return ProductCategory{}, err
		}
		_, err = s.db.ExecContext(ctx, `INSERT INTO product_categories(id,owner_id,name) VALUES(?,?,?)`, id, owner, name)
		if err != nil {
			return ProductCategory{}, invalidProduct("category name already exists or could not be saved")
		}
	} else {
		result, err := s.db.ExecContext(ctx, `UPDATE product_categories SET name=? WHERE id=? AND owner_id=?`, name, id, owner)
		if err != nil {
			return ProductCategory{}, invalidProduct("category name already exists or could not be saved")
		}
		if n, _ := result.RowsAffected(); n == 0 {
			return ProductCategory{}, ErrNotFound
		}
	}
	category := ProductCategory{ID: id, Name: name}
	if err := s.db.QueryRowContext(ctx, `SELECT count(*) FROM products WHERE owner_id=? AND category_id=?`, owner, id).Scan(&category.ProductCount); err != nil {
		return ProductCategory{}, err
	}
	return category, nil
}

func (s *Store) DeleteProductCategory(ctx context.Context, owner, id string) error {
	s.productMu.Lock()
	defer s.productMu.Unlock()
	tx, err := s.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	result, err := tx.ExecContext(ctx, `DELETE FROM product_categories WHERE id=? AND owner_id=?`, id, owner)
	if err != nil {
		return err
	}
	if n, _ := result.RowsAffected(); n == 0 {
		return ErrNotFound
	}
	_, err = tx.ExecContext(ctx, `UPDATE products SET category_id='',version=version+1,updated_at=? WHERE category_id=? AND owner_id=?`, time.Now().UnixMilli(), id, owner)
	if err != nil {
		return err
	}
	return tx.Commit()
}

const productColumns = `p.id,p.owner_id,p.name,p.brand,p.model,p.category_id,coalesce(c.name,'') AS category_name,p.image_id,p.version,p.updated_at`
const productJoin = ` FROM products p LEFT JOIN product_categories c ON c.id=p.category_id AND c.owner_id=p.owner_id `

func scanProduct(row interface{ Scan(...any) error }, p *Product, extra ...any) error {
	var updated int64
	args := []any{&p.ID, &p.OwnerID, &p.Name, &p.Brand, &p.Model, &p.CategoryID, &p.CategoryName, &p.ImageID, &p.Version, &updated}
	args = append(args, extra...)
	err := row.Scan(args...)
	p.UpdatedAt = time.UnixMilli(updated).UTC()
	if p.ImageID != "" {
		p.ImageURL = "/api/product-images/" + p.ImageID
	}
	if errors.Is(err, sql.ErrNoRows) {
		return ErrNotFound
	}
	return err
}

func (s *Store) GetProduct(ctx context.Context, owner, id string) (Product, error) {
	var p Product
	err := scanProduct(s.db.QueryRowContext(ctx, `SELECT `+productColumns+`,p.specification`+productJoin+`WHERE p.owner_id=? AND p.id=?`, owner, id), &p, &p.Specification)
	return p, err
}

func productImage(dataURL string) ([]byte, string, error) {
	if len(dataURL) > MaxProductImageBytes*4/3+100 {
		return nil, "", invalidProduct("image exceeds 2 MiB")
	}
	meta, encoded, ok := strings.Cut(dataURL, ",")
	if !ok || (meta != "data:image/png;base64" && meta != "data:image/jpeg;base64") {
		return nil, "", invalidProduct("image must be PNG or JPEG")
	}
	data, err := base64.StdEncoding.DecodeString(encoded)
	if err != nil || len(data) == 0 || len(data) > MaxProductImageBytes {
		return nil, "", invalidProduct("invalid or oversized image")
	}
	config, format, err := image.DecodeConfig(bytes.NewReader(data))
	if err != nil || config.Width <= 0 || config.Height <= 0 || int64(config.Width)*int64(config.Height) > 16_000_000 {
		return nil, "", invalidProduct("invalid image dimensions (max 16 megapixels)")
	}
	mime := "image/" + format
	if meta != "data:"+mime+";base64" {
		return nil, "", invalidProduct("image type does not match its contents")
	}
	if _, _, err = image.Decode(bytes.NewReader(data)); err != nil {
		return nil, "", invalidProduct("image cannot be decoded")
	}
	return data, mime, nil
}

func (s *Store) SaveProduct(ctx context.Context, owner, id string, in ProductInput) (Product, error) {
	in.Name = strings.TrimSpace(in.Name)
	in.Model = strings.TrimSpace(in.Model)
	in.Brand = strings.TrimSpace(in.Brand)
	in.CategoryID = strings.TrimSpace(in.CategoryID)
	if owner == "" || in.Name == "" || utf8.RuneCountInString(in.Name) > 200 || utf8.RuneCountInString(in.Model) > 160 || utf8.RuneCountInString(in.Brand) > 100 || utf8.RuneCountInString(in.Specification) > MaxProductSpecificationRunes || !utf8.ValidString(in.Specification) {
		return Product{}, invalidProduct("name is required; field length limit exceeded or invalid text")
	}
	var data []byte
	var mime string
	var err error
	if in.ImageDataURL != nil && *in.ImageDataURL != "" {
		data, mime, err = productImage(*in.ImageDataURL)
		if err != nil {
			return Product{}, err
		}
	}
	s.productMu.Lock()
	defer s.productMu.Unlock()
	tx, err := s.db.BeginTx(ctx, nil)
	if err != nil {
		return Product{}, err
	}
	defer tx.Rollback()
	imageID := ""
	version := int64(1)
	if id != "" {
		var oldVersion int64
		err = tx.QueryRowContext(ctx, `SELECT version,image_id FROM products WHERE owner_id=? AND id=?`, owner, id).Scan(&oldVersion, &imageID)
		if errors.Is(err, sql.ErrNoRows) {
			return Product{}, ErrNotFound
		}
		if err != nil {
			return Product{}, err
		}
		if oldVersion != in.Version {
			return Product{}, ErrProductConflict
		}
		version = oldVersion + 1
	} else {
		id, err = newID("prod")
		if err != nil {
			return Product{}, err
		}
	}
	if in.CategoryID != "" {
		var found string
		if err := tx.QueryRowContext(ctx, `SELECT id FROM product_categories WHERE id=? AND owner_id=?`, in.CategoryID, owner).Scan(&found); err != nil {
			if errors.Is(err, sql.ErrNoRows) {
				return Product{}, ErrNotFound
			}
			return Product{}, err
		}
	}
	if in.ImageDataURL != nil {
		imageID = ""
		if len(data) > 0 {
			sum := sha256.Sum256(append([]byte(owner+"\x00"), data...))
			imageID = "pimg_" + hex.EncodeToString(sum[:])
			if _, err = tx.ExecContext(ctx, `INSERT OR IGNORE INTO product_images(id,owner_id,content_type,data) VALUES(?,?,?,?)`, imageID, owner, mime, data); err != nil {
				return Product{}, err
			}
		}
	}
	now := time.Now().UnixMilli()
	_, err = tx.ExecContext(ctx, `INSERT INTO products(id,owner_id,name,brand,model,model_key,category_id,specification,image_id,version,updated_at) VALUES(?,?,?,?,?,?,?,?,?,?,?) ON CONFLICT(id) DO UPDATE SET name=excluded.name,brand=excluded.brand,model=excluded.model,model_key=excluded.model_key,category_id=excluded.category_id,specification=excluded.specification,image_id=excluded.image_id,version=excluded.version,updated_at=excluded.updated_at`, id, owner, in.Name, in.Brand, in.Model, productModelKey(in.Model), in.CategoryID, in.Specification, imageID, version, now)
	if err != nil {
		return Product{}, err
	}
	if _, err = tx.ExecContext(ctx, `DELETE FROM product_chunks WHERE product_id=?`, id); err != nil {
		return Product{}, err
	}
	metadata := strings.Join(productTokens(in.Name+" "+in.Brand+" "+in.Model), " ") + " " + productModelKey(in.Model)
	runes := []rune(in.Specification)
	for _, section := range splitProductSections(in.Specification) {
		content := string(runes[section.Offset : section.Offset+section.Length])
		res, err := tx.ExecContext(ctx, `INSERT INTO product_chunks(product_id,section_index,heading,start_offset,content) VALUES(?,?,?,?,?)`, id, section.Index, section.Heading, section.Offset, content)
		if err != nil {
			return Product{}, err
		}
		rowID, err := res.LastInsertId()
		if err != nil {
			return Product{}, err
		}
		if _, err = tx.ExecContext(ctx, `INSERT INTO product_chunks_fts(rowid,metadata,body) VALUES(?,?,?)`, rowID, metadata, strings.Join(productTokens(content), " ")); err != nil {
			return Product{}, err
		}
	}
	if err = tx.Commit(); err != nil {
		return Product{}, err
	}
	return s.GetProduct(ctx, owner, id)
}

func (s *Store) DeleteProduct(ctx context.Context, owner, id string, version int64) error {
	s.productMu.Lock()
	defer s.productMu.Unlock()
	tx, err := s.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	var current int64
	err = tx.QueryRowContext(ctx, `SELECT version FROM products WHERE owner_id=? AND id=?`, owner, id).Scan(&current)
	if errors.Is(err, sql.ErrNoRows) {
		return ErrNotFound
	}
	if err != nil {
		return err
	}
	if version != current {
		return ErrProductConflict
	}
	if _, err = tx.ExecContext(ctx, `DELETE FROM products WHERE owner_id=? AND id=?`, owner, id); err != nil {
		return err
	}
	return tx.Commit()
}

